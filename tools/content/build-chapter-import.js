#!/usr/bin/env node
/**
 * Generates a WordPress import file that creates every AM chapter, with its
 * city, region and map coordinates already filled in.
 *
 * Import it with Tools -> Import -> WordPress. Sixty-odd chapters appear under
 * Chapters, and the homepage globe plots them immediately.
 *
 * Re-importing is safe: WordPress matches on the post slug, so chapters are
 * updated rather than duplicated.
 *
 * Run: node tools/content/build-chapter-import.js
 */

const fs = require('fs');
const path = require('path');
const chapters = require('./chapters');

const SITE = 'https://amintl.org';
const AUTHOR = 'admin';
// A high starting id keeps these clear of anything already in the database.
const FIRST_ID = 90001;

const now = new Date();
const stamp = (d) =>
  d.toISOString().replace('T', ' ').replace(/\..+$/, '');

function cdata(value) {
  // ]]> would close the section early; split it across two sections.
  return `<![CDATA[${String(value).replace(/\]\]>/g, ']]]]><![CDATA[>')}]]>`;
}

function slugify(text) {
  return text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '') // strip accents: São -> Sao
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function meta(key, value) {
  return `
		<wp:postmeta>
			<wp:meta_key>${cdata(key)}</wp:meta_key>
			<wp:meta_value>${cdata(value)}</wp:meta_value>
		</wp:postmeta>`;
}

const items = chapters.map((row, index) => {
  const [region, city, country, lat, lng, kindOverride] = row;

  const title = `AM ${city}`;
  const slug = slugify(title);
  const location = `${city}, ${country}`;
  const kind = kindOverride || 'Campus chapter';
  const id = FIRST_ID + index;

  const body =
    kindOverride === 'Headquarters'
      ? `<p>The headquarters of Apostolos Missions International, in ${location}.</p>`
      : `<p>The AM chapter in ${location}, part of our ${region} network.</p>`;

  return `
	<item>
		<title>${cdata(title)}</title>
		<link>${SITE}/network/${slug}/</link>
		<pubDate>${now.toUTCString()}</pubDate>
		<dc:creator>${cdata(AUTHOR)}</dc:creator>
		<guid isPermaLink="false">${SITE}/?post_type=am_chapter&#38;p=${id}</guid>
		<description></description>
		<content:encoded>${cdata(body)}</content:encoded>
		<excerpt:encoded>${cdata('')}</excerpt:encoded>
		<wp:post_id>${id}</wp:post_id>
		<wp:post_date>${cdata(stamp(now))}</wp:post_date>
		<wp:post_date_gmt>${cdata(stamp(now))}</wp:post_date_gmt>
		<wp:comment_status>${cdata('closed')}</wp:comment_status>
		<wp:ping_status>${cdata('closed')}</wp:ping_status>
		<wp:post_name>${cdata(slug)}</wp:post_name>
		<wp:status>${cdata('publish')}</wp:status>
		<wp:post_parent>0</wp:post_parent>
		<wp:menu_order>${index + 1}</wp:menu_order>
		<wp:post_type>${cdata('am_chapter')}</wp:post_type>
		<wp:post_password>${cdata('')}</wp:post_password>
		<wp:is_sticky>0</wp:is_sticky>${meta('_am_location', location)}${meta('_am_kind', kind)}${meta('_am_lat', lat)}${meta('_am_lng', lng)}${meta('_am_region', region)}
	</item>`;
});

const xml = `<?xml version="1.0" encoding="UTF-8" ?>
<!--
	Apostolos Missions International - chapter directory.

	Generated by tools/content/build-chapter-import.js from the "Our Network"
	page of amintl.org. Import with Tools -> Import -> WordPress.

	${chapters.length} chapters, all with coordinates for the homepage globe.
-->
<rss version="2.0"
	xmlns:excerpt="http://wordpress.org/export/1.2/excerpt/"
	xmlns:content="http://purl.org/rss/1.0/modules/content/"
	xmlns:wfw="http://wellformedweb.org/CommentAPI/"
	xmlns:dc="http://purl.org/dc/elements/1.1/"
	xmlns:wp="http://wordpress.org/export/1.2/"
>
<channel>
	<title>AM International - Chapters</title>
	<link>${SITE}</link>
	<description>Chapter directory for the AM International theme</description>
	<pubDate>${now.toUTCString()}</pubDate>
	<language>en-US</language>
	<wp:wxr_version>1.2</wp:wxr_version>
	<wp:base_site_url>${SITE}</wp:base_site_url>
	<wp:base_blog_url>${SITE}</wp:base_blog_url>
	<wp:author>
		<wp:author_id>1</wp:author_id>
		<wp:author_login>${cdata(AUTHOR)}</wp:author_login>
		<wp:author_email>${cdata('')}</wp:author_email>
		<wp:author_display_name>${cdata(AUTHOR)}</wp:author_display_name>
		<wp:author_first_name>${cdata('')}</wp:author_first_name>
		<wp:author_last_name>${cdata('')}</wp:author_last_name>
	</wp:author>
${items.join('\n')}
</channel>
</rss>
`;

const out = path.join(__dirname, '..', '..', 'wp-theme', 'chapters-import.xml');
fs.writeFileSync(out, xml);

console.log(
  `wrote ${chapters.length} chapters -> ${path.relative(process.cwd(), out)} ` +
    `(${(xml.length / 1024).toFixed(1)} KB)`
);
