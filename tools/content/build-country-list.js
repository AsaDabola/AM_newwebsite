#!/usr/bin/env node
/**
 * Renders the mission country list as a Markdown reference.
 *
 * Usage: node tools/content/build-country-list.js [outFile]
 * Default output: docs/country-list.md
 */

const fs = require('fs');
const path = require('path');
const { COUNTRIES, FELLOWSHIPS, CORRECTIONS } = require('./countries.js');

const OUT = process.argv[2] || path.join(__dirname, '..', '..', 'docs', 'country-list.md');

const isoCount = new Set(COUNTRIES.flatMap((c) => c.iso)).size;
const byTier = (tier) => COUNTRIES.filter((c) => c.tier === tier);
const withSites = COUNTRIES.filter((c) => c.sites);

function table(list) {
  const out = [
    '| # | Country | Path | Languages | Existing sites |',
    '|---|---|---|---|---|',
  ];
  for (const c of list) {
    const paths = c.iso.map((i) => `\`/${i}/\``).join(' ');
    const name = c.covers ? `${c.name} <br><small>${c.covers.join(', ')}</small>` : c.name;
    const sites = c.sites
      ? Object.entries(c.sites).map(([k, v]) => `${k}: ${v.replace(/^https?:\/\//, '')}`).join('<br>')
      : '—';
    out.push(`| ${c.no} | ${name} | ${paths} | ${c.languages.join(', ')} | ${sites} |`);
  }
  return out;
}

const regions = [...new Set(byTier('M40').map((c) => c.region))];

const lines = [
  '# Mission country list',
  '',
  'Generated from `tools/content/countries.js`, which was extracted from',
  '`Fellowship_Websites_Status_60_Countries.xlsx`. Do not edit this file by hand —',
  'edit the data and re-run `node tools/content/build-country-list.js`.',
  '',
  `**${COUNTRIES.length} entries**, covering **${isoCount} distinct countries**.`,
  'Two entries are country groups that share one site, which is why the two',
  'numbers differ.',
  '',
  '| Tier | Entries |',
  '|---|---|',
  `| G20 mission countries | ${byTier('G20').length} |`,
  `| M40 mission countries | ${byTier('M40').length} |`,
  `| Additional priority or replacement | ${byTier('Additional').length} |`,
  `| **Total** | **${COUNTRIES.length}** |`,
  '',
  'Paths use the ISO country code as a subdirectory of the fellowship domain,',
  'so the United States is `amintl.org/us/`. Country groups hold more than one',
  'path; all of them resolve to the same site.',
  '',
  '---',
  '',
  '## G20 mission countries',
  '',
  ...table(byTier('G20')),
  '',
  '---',
  '',
  '## M40 mission countries',
  '',
];

for (const region of regions) {
  lines.push(`### ${region}`, '', ...table(byTier('M40').filter((c) => c.region === region)), '');
}

lines.push(
  '---',
  '',
  '## Additional priority or replacement countries',
  '',
  ...table(byTier('Additional')),
  '',
  '---',
  '',
  '## What already exists',
  '',
  `${withSites.length} of ${COUNTRIES.length} entries have at least one fellowship site live today.`,
  '',
  '| Country | Fellowship | Site |',
  '|---|---|---|',
  ...withSites.flatMap((c) =>
    Object.entries(c.sites).map(([f, url]) => `| ${c.name} | ${f} | ${url} |`)
  ),
  '',
  '### By fellowship',
  '',
  '| Fellowship | Headquarters | Country sites live |',
  '|---|---|---|',
  ...Object.entries(FELLOWSHIPS).map(([name, hq]) => {
    const n = withSites.filter((c) => c.sites[name]).length;
    return `| ${name} | ${hq || '—'} | ${n} |`;
  }),
  '',
  '---',
  '',
  '## Corrections to the source spreadsheet',
  '',
  '| Row | Was | Now | Why |',
  '|---|---|---|---|',
  ...CORRECTIONS.map(
    (c) => `| ${c.row} | ${c.was || '—'} | ${c.now || '—'} | ${c.why} |`
  ),
  ''
);

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${OUT}: ${COUNTRIES.length} entries, ${isoCount} countries`);
